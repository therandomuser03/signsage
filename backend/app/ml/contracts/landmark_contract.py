"""Loader/validator for landmark_contract.json.

landmark_contract.json is generated by the training notebook (Section 5b)
directly from the real MediaPipe pose-file header -- it is the authoritative
source for how the 543 landmarks are ordered. This module only loads and
sanity-checks it against this package's own hardcoded constants
(ml/preprocessing/landmarks.py); it never invents landmark ordering itself.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from app.ml.preprocessing.landmarks import (
    COORDINATES_PER_LANDMARK,
    NORMALIZATION_VERSION,
    RAW_FEATURE_DIM,
    TOTAL_LANDMARKS,
)


class LandmarkContractError(ValueError):
    """The bundle's landmark_contract.json is missing, malformed, or
    inconsistent with this package's preprocessing constants."""


@dataclass
class LandmarkContract:
    total_landmark_count: int
    coordinates_per_landmark: int
    raw_feature_dim: int
    component_order: list
    component_ranges: dict
    normalization_version: str
    max_frames: int
    final_model_input_dim: int
    raw: dict  # full parsed JSON, for anything not surfaced above

    @classmethod
    def load(cls, path: Path) -> "LandmarkContract":
        if not path.is_file():
            raise LandmarkContractError(f"landmark_contract.json not found at {path}")
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)

        errors: list = []
        if int(data.get("total_landmark_count", -1)) != TOTAL_LANDMARKS:
            errors.append(
                f"total_landmark_count={data.get('total_landmark_count')} != expected {TOTAL_LANDMARKS}"
            )
        if int(data.get("coordinates_per_landmark", -1)) != COORDINATES_PER_LANDMARK:
            errors.append(
                f"coordinates_per_landmark={data.get('coordinates_per_landmark')} != expected "
                f"{COORDINATES_PER_LANDMARK}"
            )
        if int(data.get("raw_feature_dim", -1)) != RAW_FEATURE_DIM:
            errors.append(f"raw_feature_dim={data.get('raw_feature_dim')} != expected {RAW_FEATURE_DIM}")
        if data.get("normalization_version") != NORMALIZATION_VERSION:
            errors.append(
                f"normalization_version={data.get('normalization_version')!r} != expected "
                f"{NORMALIZATION_VERSION!r} (this backend's ml/preprocessing implementation)"
            )
        mask = data.get("full_feature_mask")
        if not isinstance(mask, list) or len(mask) != RAW_FEATURE_DIM:
            errors.append(
                f"full_feature_mask has length {len(mask) if isinstance(mask, list) else 'N/A'}, "
                f"expected {RAW_FEATURE_DIM}"
            )
        if errors:
            raise LandmarkContractError(
                "landmark_contract.json failed validation:\n  - " + "\n  - ".join(errors)
            )

        return cls(
            total_landmark_count=int(data["total_landmark_count"]),
            coordinates_per_landmark=int(data["coordinates_per_landmark"]),
            raw_feature_dim=int(data["raw_feature_dim"]),
            component_order=list(data["component_order"]),
            component_ranges={k: list(v) for k, v in data["component_ranges"].items()},
            normalization_version=str(data["normalization_version"]),
            max_frames=int(data["max_frames"]),
            final_model_input_dim=int(data["final_model_input_dim"]),
            raw=data,
        )
